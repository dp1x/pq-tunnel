/// Decode a lowercase hex string into bytes. Test-only helper.
pub fn unhex(hex: &str) -> Vec<u8> {
    assert_eq!(hex.len() % 2, 0, "odd-length hex string: {}", hex);
    (0..hex.len() / 2)
        .map(|i| u8::from_str_radix(&hex[2 * i..2 * i + 2], 16).expect("valid hex digit"))
        .collect()
}

